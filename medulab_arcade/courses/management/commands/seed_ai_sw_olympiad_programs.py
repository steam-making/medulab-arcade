def seed_past_exams(program, exams, guides, key_prefix, grade_label, legacy_keys, example_answers=None):
    Item.objects.filter(chapter__program=program, key__in=legacy_keys).delete()

    for exam in exams:
        round_number = exam["round"]
        chapter, _ = Chapter.objects.update_or_create(
            program=program,
            number=round_number,
            defaults={
                "title": f"제{round_number}회 기출문제",
                "content": exam["title"],
            },
        )

        for question_number, body in exam["questions"]:
            hint_text = build_past_exam_hint(round_number, question_number, guides)
            item, _ = Item.objects.update_or_create(
                key=f"{key_prefix}_round_{round_number}_question_{question_number}",
                defaults={
                    "chapter": chapter,
                    "number": int(question_number),
                    "title": f"문제 {question_number}",
                    "item_type": "olympiad",
                    "explain_html": build_question_html(round_number, question_number, body, grade_label),
                    "hint": hint_text,
                },
            )
            seed_sub_questions_for_item(
                item, question_number, body, hint_text,
                round_number=round_number, example_answers=example_answers,
            )

    seeded_chapter_numbers = {exam["round"] for exam in exams}
    program.chapters.exclude(number__in=seeded_chapter_numbers).filter(items__isnull=True).delete()


def parse_sub_questions(question_number, body):
    """
    질문 본문에서 하위문제(X-1., X-2. ...) 를 파싱.
    반환: [(sub_number, sub_text), ...]  — 없으면 [(1, body)]
    """
    pattern = re.compile(
        rf'{re.escape(question_number)}-(\d+)\.\s*(.*?)(?=(?:{re.escape(question_number)}-\d+\.)|$)',
        re.DOTALL,
    )
    matches = pattern.findall(body)
    if not matches:
        return [(1, body.strip())]
    return [(int(num), text.strip()) for num, text in matches]


def seed_sub_questions_for_item(item, question_number, body, hint_text="", round_number=None, example_answers=None):
    """Item 에 연결된 OlympiadSubQuestion 을 생성/갱신."""
    subs = parse_sub_questions(question_number, body)
    existing_numbers = set(
        item.sub_questions.values_list("number", flat=True)
    )
    ea_dict = example_answers or {}
    for sub_num, sub_text in subs:
        ea = ea_dict.get((round_number, question_number, sub_num), "")
        defaults = {
            "question_text": sub_text,
            "hint": hint_text,
        }
        if ea:
            defaults["example_answer"] = ea
        OlympiadSubQuestion.objects.update_or_create(
            item=item,
            number=sub_num,
            defaults=defaults,
        )
        existing_numbers.discard(sub_num)
    # 시드에 없는 번호 삭제
    if existing_numbers:
        item.sub_questions.filter(number__in=existing_numbers).delete()


