def build_past_exam_hint(round_number, question_number, guides=None):
    if guides is None:
        guides = PAST_EXAM_GUIDES
    guide = guides.get((round_number, question_number))
    if not guide:
        return PAST_EXAM_HINT
    return (
        "[문제 분석]\n"
        f"{guide['analysis']}\n\n"
        "[예시답안 요약 힌트]\n"
        f"{guide['answer_hint']}"
    )


